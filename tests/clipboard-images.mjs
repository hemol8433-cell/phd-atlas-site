import assert from "node:assert/strict";
import fs from "node:fs/promises";
const moduleSource=await fs.readFile(new URL("../docs/clipboard-images.js",import.meta.url),"utf8");
const screenshots=await import("data:text/javascript;charset=utf-8,"+encodeURIComponent(moduleSource));
const id="f41c8ae1-1e4a-4d21-8f7d-f5d9a69450d1";
const token=screenshots.imageMarker(id);
assert.equal(token,"[[截图:"+id+"]]");
assert.deepEqual(screenshots.imageIds("A "+token+" B "+token),[id,id]);
assert.deepEqual(screenshots.imageIds("ordinary text or fake [[截图:bad]]"),[]);
assert.throws(()=>screenshots.imageMarker("../secret"));
assert.deepEqual(screenshots.appendImageMarker("Before",id,6,6).value,"Before\n"+token+"\n");
const mid=screenshots.appendImageMarker("Before after",id,3,7);
assert.equal(mid.value,"Bef\n"+token+"\nafter");
assert.equal(screenshots.appendImageMarker("text",id,4,4,8),null,"Never exceed the editor maxlength");
assert.equal(screenshots.supportedImage({type:"image/png",size:1024}),true);
assert.equal(screenshots.supportedImage({type:"image/jpeg",size:1024}),true);
assert.equal(screenshots.supportedImage({type:"image/svg+xml",size:1024}),false,"SVG is not an allowed paste image");
assert.equal(screenshots.supportedImage({type:"image/png",size:26*1024*1024}),false,"Uploads over 25MB are rejected");
assert.equal(screenshots.supportedImage({type:"image/png",size:0}),false);
const file={type:"image/png",size:120};
const clipboard={items:[{kind:"string",type:"text/plain"}, {kind:"file",type:"image/png",getAsFile:()=>file}]};
assert.deepEqual(screenshots.clipboardImages(clipboard),[file]);
assert.deepEqual(screenshots.clipboardImages({items:[{kind:"file",type:"application/pdf",getAsFile:()=>file}]}),[]);
assert(moduleSource.includes('const BUCKET = "phd-atlas-private"'),"Images must use the private bucket");
assert(moduleSource.includes('uid+"/uploads/images/clipboard-"'),"Image paths must be owner scoped");
assert(!moduleSource.includes("getPublicUrl"),"Never expose private images by public URL");
const research=await fs.readFile(new URL("../docs/research.js",import.meta.url),"utf8");
const html=await fs.readFile(new URL("../docs/app.html",import.meta.url),"utf8");
assert(research.includes('installClipboardImages({session,getData:()=>db,save,toast})'),"Attach to private authenticated workspace");
assert(html.includes("clipboard-images.css"),"Paste indicator and screenshot viewer styles should load");
const vaultSource=await fs.readFile(new URL("../docs/vault.js",import.meta.url),"utf8");
assert(vaultSource.includes('id="vaultPaste"'),"Private vault should expose a focusable paste target");
assert(vaultSource.includes('pasteZone.addEventListener("paste"'),"Private vault clipboard target should upload images");
assert(vaultSource.includes('prefix+"images/"'),"Private vault screenshot uploads must stay inside the owner namespace");
console.log("PASS: secure clipboard image types, 25MB limit, persistent image markers, editor insertion, and private app wiring");
